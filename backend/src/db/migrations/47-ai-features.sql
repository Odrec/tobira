-- AI Features Tables for Separate Microservice
-- Added: 2025-10-09
-- Description: Database schema for AI-powered features (summaries, quizzes, transcripts)
-- managed by separate microservice. These tables are accessed by the external AI service
-- and do not affect core Tobira functionality.

-- ============================================
-- Video Transcripts
-- ============================================
-- Stores video transcripts uploaded externally or synced from Opencast.
-- The AI microservice uses these as input for generating summaries and quizzes.

create table if not exists video_transcripts (
    id bigserial primary key,
    event_id bigint not null references all_events(id) on delete cascade,
    language varchar(10) not null default 'en',
    content text not null,
    source varchar(50) not null default 'manual_upload',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(event_id, language)
);

create index idx_video_transcripts_event_id on video_transcripts(event_id);

comment on table video_transcripts is 
    'Video transcripts managed by AI microservice. Used as input for AI features.';
comment on column video_transcripts.source is 
    'Source of transcript: manual_upload, opencast, auto_generated';


-- ============================================
-- AI-Generated Summaries
-- ============================================
-- Stores AI-generated summaries of video content.
-- Generated by the external AI microservice using OpenAI API.

create table if not exists ai_summaries (
    id bigserial primary key,
    event_id bigint not null references all_events(id) on delete cascade,
    language varchar(10) not null default 'en',
    summary text not null,
    model varchar(50) not null,
    processing_time_ms integer,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(event_id, language)
);

create index idx_ai_summaries_event_id on ai_summaries(event_id);

comment on table ai_summaries is 
    'AI-generated video summaries from external microservice';
comment on column ai_summaries.model is 
    'OpenAI model used (e.g., gpt-3.5-turbo, gpt-4)';
comment on column ai_summaries.processing_time_ms is 
    'Time taken to generate summary in milliseconds';


-- ============================================
-- AI-Generated Quizzes
-- ============================================
-- Stores AI-generated interactive quizzes for videos.
-- Quiz data is stored as JSONB for flexibility.

create table if not exists ai_quizzes (
    id bigserial primary key,
    event_id bigint not null references all_events(id) on delete cascade,
    language varchar(10) not null default 'en',
    quiz_data jsonb not null,
    model varchar(50) not null,
    processing_time_ms integer,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(event_id, language),
    constraint valid_quiz_data check (
        jsonb_typeof(quiz_data) = 'object' 
        and quiz_data ? 'questions'
        and jsonb_typeof(quiz_data->'questions') = 'array'
    )
);

create index idx_ai_quizzes_event_id on ai_quizzes(event_id);

comment on table ai_quizzes is 
    'AI-generated interactive quizzes from external microservice';
comment on column ai_quizzes.quiz_data is 
    'Quiz questions and metadata in JSON format';


-- ============================================
-- AI Configuration
-- ============================================
-- Configuration and feature flags for AI features.
-- Allows runtime control without code changes.

create table if not exists ai_config (
    id bigserial primary key,
    key varchar(100) not null unique,
    value jsonb not null,
    description text,
    updated_at timestamptz not null default now()
);

comment on table ai_config is 
    'Configuration for AI features (feature flags, model selection, etc.)';

