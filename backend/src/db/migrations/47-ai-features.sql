-- ============================================
-- AI Processing Queue (Optional - Phase 2)
-- ============================================
-- Queue for asynchronous AI processing jobs.
-- Not used in MVP but included for future expansion.

create table if not exists ai_processing_queue (
    id bigserial primary key,
    event_id bigint not null references all_events(id) on delete cascade,
    task_type varchar(50) not null,
    language varchar(10) not null default 'en',
    priority integer default 0,
    status varchar(20) not null default 'pending',
    retry_count integer default 0,
    max_retries integer default 3,
    error_message text,
    scheduled_at timestamptz not null default now(),
    started_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz not null default now(),
    unique(event_id, task_type, language)
);

create index idx_ai_queue_status on ai_processing_queue(status, scheduled_at);
create index idx_ai_queue_task on ai_processing_queue(task_type, status);

comment on table ai_processing_queue is 
    'Queue for async AI processing jobs (Phase 2 feature)';
comment on column ai_processing_queue.task_type is 
    'Type of task: summary, quiz, chat_index';
comment on column ai_processing_queue.status is 
    'Status: pending, processing, completed, failed';